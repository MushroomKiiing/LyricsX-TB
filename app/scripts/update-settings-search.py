#!/usr/bin/env python3
"""Generate offline search metadata from public settings copy, never runtime/user data."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'Sources/LyricsXApp'
OUTPUT = APP / 'SettingsSearchIndex.swift'
STRING = r'"((?:[^"\\]|\\.)*)"'
PATTERN = re.compile(r'(?:SettingRow|SettingToggle|SettingSlider|SettingsCard|InterfaceThemePicker)\(title: ' + STRING)
SKIP = {'等待系统允许', '联动启动等待系统允许', '音频采集'}
ALIASES = {
    '随网易云启动': '自动打开 联动 自启动 网易云音乐 netease 隐私 后台 监听',
    '登录时启动': '开机 自动启动 login',
    '恢复全宽的等待时间': '1–15 秒 延迟 闲置 时间 全屏',
    '闲置后自动全宽': '全屏 自动切换', '固定全宽显示': '全屏 居中',
    '翻译与下一句': '显示翻译 关闭翻译 隐藏翻译 辅助内容 双语 译文',
    '显示歌词翻译': '双语 中文 原文 译文 左右',
    '补充高清封面': '专辑 图片 清晰 模糊 隐私 缓存 网易云 netease',
    'Touch Bar': 'TB 触控条 白色 常规 字体',
    '歌词字体': '字型 样式', '来源顺序': '网易云 酷狗 QQMusic Kugou NetEase 来源 优先级',
}
DETAILS = {
    '翻译与下一句': '选择悬浮窗原文下方的内容。选择“仅下一句”或“都不显示”可隐藏悬浮窗翻译。',
    '鼠标经过时隐藏': '锁定悬浮窗后，鼠标经过时暂时隐藏内容，离开后恢复。',
    '窗口宽度': '调整悬浮窗可用宽度；自动高度开启时采用固定宽度。',
    '显示歌词翻译': 'Touch Bar 原文在左、已有译文在右；需先开启翻译总开关。',
    'Touch Bar 非官方定制版': '查看本地版本号与开源项目署名。',
    '恢复全部歌词搜索': '清空歌曲、专辑的停用记录及相关例外，恢复歌词搜索。',
}

def unquote(text):
    if r'\(' in text: return None
    return json.loads('"' + text + '"')

def records():
    entries = {}
    def add(section, title, detail, keywords='', target=None):
        if title in SKIP: return
        entries[(section, title)] = dict(section=section, title=title, detail=DETAILS.get(title, detail),
                                        keywords=keywords or ALIASES.get(title, ''), target=target)
    def collect(section, text):
        matches = list(PATTERN.finditer(text))
        for i, match in enumerate(matches):
            title = unquote(match[1])
            if not title: continue
            fragment = text[match.end():matches[i+1].start() if i+1 < len(matches) else len(text)]
            detail = re.search(r',\s*detail:\s*' + STRING, fragment)
            detail = unquote(detail[1]) if detail else None
            impact = re.search(r',\s*impact:\s*' + STRING, fragment)
            impact = unquote(impact[1]) if impact else ''
            add(section, title, detail or '查看对应设置。', ALIASES.get(title, '') + ' ' + (impact or ''))
    view = (APP/'PreferencesView.swift').read_text()
    for section, name in [('general','generalSettings'),('player','playerSettings'),('overlay','overlaySettings'),
                          ('appearance','appearanceSettings'),('lyrics','lyricSettings'),('sync','synchronizationSettings'),('touchBar','touchBarSettings'),
                          ('effects','effectSettings'),('effects','hdrSettings'),('sources','sourceSettings'),
                          ('developer','developerSettings'),('about','aboutSettings')]:
        match = re.search(r'    private var ' + name + r': some View \{(.*?)(?=\n    private (?:var|func) |\Z)', view, re.S)
        if not match: raise ValueError('Missing settings view: ' + name)
        collect(section, match[1])
    for section, file in [('typography','LyricTypographySettings.swift'),('general','HotkeySettingsView.swift'),
                          ('sync','GlobalLyricOffsetSettings.swift'),('overlay','OverlayTextSpacing.swift'),
                          ('lyrics','MainLyricPosition.swift'),('sources','AppleMusicCloudSettingsView.swift')]:
        collect(section, (APP/file).read_text())
    for record in [
        ('manual','使用说明','详细图文教程，包含播放器、Touch Bar、悬浮窗、翻译、外观、歌词同步与缓存。'),
        ('general','悬浮歌词','设置显示或隐藏悬浮窗的全局快捷键。'),
        ('general','主窗口','设置打开主窗口的全局快捷键。'),
        ('sync','通用歌词偏移','以秒输入所有歌曲的歌词偏移，支持毫秒精度。'),
        ('appearance','底色透明度','调整 Liquid Glass 的底色透明度。'),
        ('appearance','透明度','调整磨砂阅读背景的透明度。'),
        ('appearance','悬浮窗样式','选择 Liquid Glass 或磨砂阅读。'),
        ('effects','HDR 亮度倍数','设置长音辉光的目标亮度倍数，实际效果取决于屏幕能力。'),
        ('typography','恢复字体与颜色','恢复字体、手动颜色、逐字配色与封面跟随的默认设置。'),
    ]: add(*record)
    return list(entries.values())

TAIL = '''    static func results(for query: String) -> [SettingsSearchEntry] {
        let terms = query.split(whereSeparator: \\.isWhitespace).map { normalized(String($0)) }.filter { !$0.isEmpty }
        guard !terms.isEmpty else { return [] }
        return entries.filter { entry in
            let sectionAliases = entry.section == .touchBar ? "Touch Bar touchbar TB 触控条" : ""
            let text = normalized([entry.section.rawValue, sectionAliases, entry.title, entry.detail, entry.keywords].joined(separator: " "))
            return terms.allSatisfy { text.contains($0) }
        }
    }

    private static func normalized(_ text: String) -> String {
        text.folding(options: [.caseInsensitive, .diacriticInsensitive, .widthInsensitive], locale: .current)
            .filter { !$0.isWhitespace && !$0.isPunctuation }
    }
}
'''

def generate(entries):
    lines = ['// Generated by scripts/update-settings-search.py from public UI labels. Do not edit by hand.',
             'import Foundation', '', 'struct SettingsSearchEntry: Identifiable, Sendable {',
             '    let section: SettingsSection', '    let title: String', '    let detail: String',
             '    var keywords = ""', '    var anchor: String { title }',
             '    var id: String { section.id + ":" + title }', '}', '', 'enum SettingsSearchIndex {',
             '    // No live values, song metadata, files, tokens or network are searched.',
             '    static let entries: [SettingsSearchEntry] = [']
    q = lambda value: json.dumps(value, ensure_ascii=False)
    for e in entries:
        lines.append('        .init(section: .%s, title: %s, detail: %s, keywords: %s),' %
                     (e['section'],q(e['title']),q(e['detail']),q(e['keywords'].strip())))
    return '\n'.join(lines + ['    ]','',TAIL])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); content = generate(records())
    if args.check:
        if OUTPUT.read_text() != content: raise SystemExit('Settings search copy is stale; run scripts/update-settings-search.py')
        print('Settings search copy is current.')
    else:
        OUTPUT.write_text(content); print('Indexed %d public settings entries.' % len(records()))
